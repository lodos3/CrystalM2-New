using System;
using System.Collections.Generic;

namespace CrystalM2.Rendering.Core
{
    // NON-PREMULTIPLIED BGRA matches the original Mir sprite decoder.
    // The primary art pass deliberately does not run normal mapping, tinting,
    // ambient multiplication or replacement silhouette shadows.
    public enum SpriteBlend : byte
    {
        NonPremultiplied = 0,
        Additive = 1
    }

    public readonly record struct BakedSpriteCommand(
        int TextureId, float X, float Y, int Width, int Height, SpriteBlend Blend,
        byte TintR, byte TintG, byte TintB, byte TintA,
        bool RecalculateNormals, bool CastNewShadow)
    {
        public bool IsVisible(int viewWidth, int viewHeight)
        {
            return Width > 0 && Height > 0 && viewWidth > 0 && viewHeight > 0 &&
                   X < viewWidth && Y < viewHeight &&
                   X + (double)Width > 0 && Y + (double)Height > 0;
        }
    }

    public static class BakedArtPolicy
    {
        public static byte[] CopyBgraExact(ReadOnlySpan<byte> rawBgra, int width, int height)
        {
            if (width <= 0 || height <= 0 ||
                (long)width * height * 4 != rawBgra.Length)
                throw new ArgumentException("Exact tightly packed BGRA image required.");
            return rawBgra.ToArray(); // No gamma, colour-key, dither or premultiply.
        }

        public static BakedSpriteCommand ForArtwork(int textureId, float x, float y,
                                                      int width, int height)
        {
            Validate(textureId, x, y, width, height);
            return new BakedSpriteCommand(textureId, x, y, width, height,
                SpriteBlend.NonPremultiplied, 255, 255, 255, 255,
                RecalculateNormals: false, CastNewShadow: false);
        }

        // Light is a SEPARATE draw using a separate art/texture source. It is
        // never generated by altering the underlying baked artwork's pixels.
        public static BakedSpriteCommand ForExplicitGlow(
            int textureId, float x, float y, int width, int height,
            byte red, byte green, byte blue, byte opacity)
        {
            Validate(textureId, x, y, width, height);
            return new BakedSpriteCommand(textureId, x, y, width, height,
                SpriteBlend.Additive, red, green, blue, opacity,
                RecalculateNormals: false, CastNewShadow: false);
        }

        private static void Validate(int id, float x, float y, int width, int height)
        {
            if (id < 0 || width <= 0 || height <= 0 ||
                !float.IsFinite(x) || !float.IsFinite(y))
                throw new ArgumentException("Invalid sprite command.");
        }
    }

    public readonly record struct SpriteRun(int Start, int Count,
                                           int TextureId, SpriteBlend Blend);

    public static class SpriteRunPlanner
    {
        // Batch ONLY adjacent compatible sprites: global texture sorting would
        // break Mir's back/middle/actor/front/overlay draw order.
        public static IReadOnlyList<SpriteRun> GroupAdjacent(IReadOnlyList<BakedSpriteCommand> commands)
        {
            if (commands == null) throw new ArgumentNullException(nameof(commands));
            var runs = new List<SpriteRun>();
            int first = 0;
            while (first < commands.Count)
            {
                BakedSpriteCommand current = commands[first];
                int end = first + 1;
                while (end < commands.Count &&
                       commands[end].TextureId == current.TextureId &&
                       commands[end].Blend == current.Blend)
                    end++;

                runs.Add(new SpriteRun(first, end - first, current.TextureId, current.Blend));
                first = end;
            }
            return runs;
        }
    }
}
